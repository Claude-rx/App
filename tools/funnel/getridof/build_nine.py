def sync():
    """Copy the mouse-pouches funnel to this slug (everything but its sales page and its four offer pages)."""
    if CAMP.exists():
        if not (CAMP / MARKER).is_file(): raise SystemExit(f'{CAMP} exists and was not made by this script')
        shutil.rmtree(CAMP)
    shutil.copytree(SRC_CAMP, CAMP, ignore=shutil.ignore_patterns('index.html', 'pdp.js', 'upsell.html', 'downsell.html', 'upsell-2.html', 'downsell-2.html'))
    (CAMP / MARKER).write_text('Generated by tools/funnel/getridof/build_nine.py from src/mouse-pouches. Do not edit: edit the generators.\n')
    left = [p.relative_to(CAMP).as_posix() for p in CAMP.rglob('*') if p.suffix in ('.html', '.js', '.css') and f'/{BASE}/' in p.read_text(errors='ignore')]
    if left: raise SystemExit(f'hard-coded /{BASE}/ paths in the copied funnel: {left}')


def campaign_key():
    """Campaign 2796's public key. Source of truth: the clone's run manifest (gitignored); mirrored into
    nine/campaign.json (committed, like the other funnels' keys: it is the key every browser receives)."""
    saved = HERE / 'campaign.json'
    if CLONE_MANIFEST.is_file():
        m = json.loads(CLONE_MANIFEST.read_text())
        c = m.get('campaign') or {}
        if c.get('api_key') and c.get('id') and m.get('inventory_complete'):
            saved.write_text(json.dumps({'campaign_id': c['id'], 'name': c.get('name'), 'cloned_from': m.get('source_campaign_id'), 'api_key': c['api_key']}, indent=2) + '\n')
    if not saved.is_file(): raise SystemExit('no campaign for this funnel: run next-campaigns-create (clone of 2362) first')
    c = json.loads(saved.read_text())
    return c['api_key'], f"campaign {c['campaign_id']} ({c.get('name')})"


def configure():
    key, which = campaign_key()
    cfg = CAMP / 'assets/config.js'
    c, n = re.subn(r"(apiKey:\s*)(['\"])[^'\"]*\2", lambda m: f"{m.group(1)}'{key}'", cfg.read_text(), count=1)
    assert n == 1, 'apiKey line not found in config.js'
    cfg.write_text(c)
    data_f = ROOT / 'campaigns/getridof/_data/campaigns.json'
    data = json.loads(data_f.read_text())
    entry = dict(data[BASE])
    entry.update(name=NAME, description='9 reasons these plant-oil pouches keep mice out where traps, poison, sprays and other pouches failed. 90-day money-back guarantee.')
    data[SLUG] = entry
    data_f.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    return entry, which


def expert():
    """The authority block. Empty unless expert.json is approved and complete (a real person, in their own words)."""
    f = ROOT / 'brand/getridof/expert.json'
    e = json.loads(f.read_text()) if f.is_file() else {}
    need = ('name', 'credentials', 'bio', 'photo_file', 'quote')
    if e.get('approved') is not True or not all(str(e.get(k) or '').strip() for k in need): return '', False
    photo = SECTIONS / e['photo_file']
    if not photo.is_file(): raise SystemExit(f'expert.json names a photo that is not in {SECTIONS}: {e["photo_file"]}')
    data, _ = lp.webp(photo, 168, 80, 1.0)
    (OUT / 'expert.webp').write_bytes(data)
    x = html_mod.escape
    who = x(e['credentials']) + (' · ' + x(e['organization']) if e.get('organization') else '')
    return (f'  <div class="xp"><img src="/{SLUG}/n9/expert.webp" alt="{x(e["name"])}" width="84" height="84" loading="lazy">'
            f'<div><b>{x(e["name"])}</b><small>{who}</small><p>“{x(e["quote"])}”</p><i>{x(e.get("disclosure") or "")}</i></div></div>'), True


def checkout():
    """The reference checkout's shipping step: first and last name side by side, then country and the address line;
    the rest of the address and the phone appear once an address is typed."""
    f = CAMP / 'checkout.html'
    s = f.read_text()
    def rep(a, b):
        nonlocal s
        assert s.count(a) == 1, (a[:70], s.count(a))
        s = s.replace(a, b)
    rep('address_form:\n  label_style: inset\n  gated: false\n', 'address_form:\n  label_style: inset\n  gated: true\n')
    # The sales page links here with ?forceBundleId=main:buy3, and that stays in the address bar. A phone browser reloads
    # a background tab, which would re-apply buy3 over a choice the buyer made here (for example one-time, 1 pack). So
    # the first visit records the parameter it applied, and a reload with the same parameter gets the buyer's last choice
    # (sessionStorage.gro_bundle, written by the script below) in its place, before the Campaign Cart SDK reads the URL.
    keep = ("<script>(function(){try{var q=/([?&]forceBundleId=)([^&#]*)/i.exec(location.search);if(!q)return;var v=decodeURIComponent(q[2]),"
            "seen=sessionStorage.getItem('gro_fb'),own=sessionStorage.getItem('gro_bundle');"
            "if(seen===v&&own&&/^(buy|ot)[13]$/.test(own)&&v!=='main:'+own){history.replaceState(history.state,'',location.pathname+"
            "location.search.replace(q[0],q[1]+encodeURIComponent('main:'+own))+location.hash);sessionStorage.setItem('gro_fb','main:'+own)}else sessionStorage.setItem('gro_fb',v)}catch(e){}})();</script>\n")
    rep('<script>(function(){var m=/[?&]forceBundleId=main', keep + '<script>(function(){var m=/[?&]forceBundleId=main')
    rep('<div class="gro-addr"><div data-next-address="shipping"',
        '<div class="form-group gro-names">'
        '<div class="form-input"><label for="shipping_fname" class="label-checkout">First Name</label><input autocomplete="given-name" placeholder="First Name*" maxlength="256" name="shipping_fname" data-name="Shipping First Name" type="text" id="shipping_fname" data-next-checkout-field="fname" class="input-flds"></div>'
        '<div class="form-input"><label for="shipping_lname" class="label-checkout">Last Name</label><input autocomplete="family-name" placeholder="Last Name*" maxlength="256" name="shipping_lname" data-name="Shipping Last Name" type="text" id="shipping_lname" data-next-checkout-field="lname" class="input-flds"></div>'
        '</div>\n                              <div class="gro-addr"><div data-next-address="shipping"')
    # Subscribe & Save is selected by default, so its refill size, schedule and price are stated where it is chosen.
    # The figures are the ones in the checkout's own Automatic Refills terms (gro-refill-terms.html); if those change, this stops.
    terms = (CAMP / '_includes/gro-refill-terms.html').read_text()
    for must in ('1 pack every 30 days for $34.99', '3 packs every 90 days for $104.97'):
        assert must in terms, f'refill terms changed: {must}'
    rep('</span> today.</p><p class="gro-sw__o">',
        '</span> today.<small class="gro-sw__r">Then <span class="gro-rt gro-rt--buy1">1 pack every 30 days for $34.99</span>'
        '<span class="gro-rt gro-rt--buy3">3 packs every 90 days for $104.97</span>, free shipping, until you cancel. Skip or cancel anytime.</small></p><p class="gro-sw__o">')
    rep('<i>Lowest price · skip or cancel anytime</i>', '<i>Lowest price today · skip or cancel anytime</i>')
    rep('Items in your cart are in high demand. Up to 68% off. Ends in', 'Early Black Friday pricing ends Dec 1. Up to 68% off. Ends in')
    rep('100% refund valid for 90 days. No questions asked.', "If mice haven't left within 90 days, we refund your purchase in full.")
    rep('Money back, no questions', 'Full refund if mice stay')
    rep('Refills ship automatically at $34.99 a pack. Skip or cancel anytime.', 'Subscriber refills are $34.99 a pack; skip or cancel anytime.')
    f.write_text(s)
    rt = CAMP / '_includes/gro-refill-terms.html'
    a = 'Each pack lasts about a month, so your refill ships when it runs out:'
    assert terms.count(a) == 1, 'refill terms wording changed'
