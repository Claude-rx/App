def offers():
    """The two offer pages: the offer shell of the starter (tier cards the SDK prices), with the quiz in front of it."""
    tpl = (ROOT / 'tools/funnel/getridof/olympus-upsell-single.template.html').read_text().split('---', 2)[2]
    tpl = tpl.replace("    {% campaign_include 'countdown-timer.html' countdown_timer=countdown_timer %}\n", '')
    hero = "    {% campaign_include 'upsell/hero.html' upsell_hero=upsell_hero %}\n"
    offer = "    {% campaign_include 'upsell/offer.html' %}\n"
    body = "    {% campaign_include 'upsell/body.html' upsell_body=upsell_body %}\n"
    assert hero in tpl and offer in tpl and body in tpl
    tpl = tpl.replace(hero, "    {% campaign_include 'gro-offer-badges.html' badge_note=badge_note %}\n" + hero)
    tpl = tpl.replace(offer, "    {% if gro_quiz %}{% campaign_include 'gro-quiz.html' %}{% endif %}\n    <div id=\"gro-plan\">\n" + offer + "    </div>\n")
    tpl = tpl.replace(body, "    {% campaign_include 'gro-house-map.html' map_title=map_title map_intro=map_intro %}\n" + body)
    for name, o in OFFERS.items():
        (CAMP / f'{name}.html').write_text(offer_page(o) + tpl, encoding='utf-8')
    quiz = (HERE / 'quiz.html').read_text()
    assert f'/{BASE}/' not in quiz
    (CAMP / '_includes/gro-quiz.html').write_text('{%- comment -%} GENERATED by tools/funnel/getridof/build_nine.py from nine/quiz.html. {%- endcomment -%}\n' + quiz, encoding='utf-8')
    (CAMP / 'assets/js/gro-quiz.js').write_text((HERE / 'quiz.js').read_text(), encoding='utf-8')
    f = CAMP / 'checkout.html'
    s = f.read_text()
    assert re.search(r'^next_url: upsell\.html$', s, re.M), 'checkout does not continue to the first offer'


def main():
    sync()
    camp, which = configure()
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    standins = []
    for name, (src, width, qual, *crop) in IMAGES.items():
        if not (SECTIONS / src).is_file() and src in FALLBACK:
            standins.append(f'{name} <- {FALLBACK[src]}'); src = FALLBACK[src]
        data, _ = lp.webp(SECTIONS / src, width, qual, *crop)
        (OUT / f'{name}.webp').write_bytes(data); total += len(data)
    hero, _ = lp.webp(SECTIONS / HERO[0], *HERO[1:])
    (OUT / 'hero.webp').write_bytes(lp.webp(SECTIONS / HERO[0], 1100, 76, HERO[3])[0])

    pdp = (ROOT / 'tools/funnel/getridof/lp/page.html').read_text()
    top = ls.block(pdp, '<header class="top">', '</header>')
    demo = ls.block(pdp, '<figure class="demo">', '</figure>')
    buy = ls.block(pdp, '<div class="ofr" id="gro-buy">', '<!--/ofr-->')     # the offer card (no prices; the choice is made in the checkout)
    assert buy.count('<div') == buy.count('</div>'), 'offer card block is not balanced'
    foot = ls.block(pdp, '<footer class="ft">', '</footer>')
    ls.SLUG = SLUG                                   # the review wall and comment thread link this funnel's own images
    wall, thread = ls.wall(), ls.thread()
    xp, has_expert = expert()

    key = camp.get('axon_event_key') or ''
    if key and not re.fullmatch(r'[0-9a-fA-F-]{36}', key): raise SystemExit('axon_event_key is not an event key')
    axon = lp.axon_head(camp)
    tags, on = lp.tracking_tags(camp)
    css = (ROOT / 'tools/funnel/getridof/lp/lp.css').read_text() + '\n' + (ROOT / 'tools/funnel/getridof/listicle/ls.css').read_text() + '\n' + (HERE / 'n9.css').read_text()
    css = re.sub(r'\s*\n\s*', '', re.sub(r'/\*.*?\*/', '', css, flags=re.S))
    js = re.sub(r'/\*.*?\*/', '', (ROOT / 'tools/funnel/getridof/lp/lp.js').read_text(), flags=re.S)
    js = re.sub(r'\n\s+', '\n', js).strip()
    html = (HERE / 'page.html').read_text()
    for token, value in (('@@CSS@@', css), ('@@JS@@', js), ('@@AXON_HEAD@@', axon), ('@@FUNNEL@@', camp['name']), ('@@TOP@@', top),
                         ('@@HERO_DATA@@', 'data:image/webp;base64,' + base64.b64encode(hero).decode()), ('@@DEMO@@', demo), ('@@BUY@@', buy),
                         ('@@WALL@@', wall), ('@@THREAD@@', thread), ('@@EXPERT@@', xp), ('@@FOOTER@@', foot),
                         ('@@TRACKING@@', lp.SDK.replace('%VER%', camp['sdk_version']) + ('\n' + tags if tags else ''))):
        assert html.count(token) == 1, token
        html = html.replace(token, value)
    html = html.replace(f'/{BASE}/', f'/{SLUG}/')          # sales-page blocks and the script point at this funnel's own pages
    assert '@@' not in html and '{%' not in html and '{{' not in html and '</script' not in js.lower()
    assert f'/{BASE}' not in html and not re.search(r'sofyre', html, re.I)
    assert html.count('<span class="rs__n">') == 9, 'the page must carry nine reasons'
    front = ('---\npage_layout: pdp.html\ntitle: "9 Reasons These Pouches Work When Everything Else Didn\'t – Get Rid Of"\npage_type: product\n'
             '# Generated by tools/funnel/getridof/build_nine.py from tools/funnel/getridof/nine/ — edit those, not this file.\n---\n')
    (CAMP / 'index.html').write_text(front + '{% raw %}' + html + '{% endraw %}\n', encoding='utf-8')
    checkout()
    offers()
    print(f'wrote {CAMP / "index.html"}: {len(html) / 1024:.0f} KB (hero inline {len(hero) / 1024:.0f} KB, css {len(css) / 1024:.0f} KB, js {len(js) / 1024:.0f} KB); '
          f'{len(IMAGES)} images, {total / 1024:.0f} KB lazy; expert block: {"shown" if has_expert else "off (expert.json not approved)"}; '
          f'tracking tags on: {on or "none"}; api key: {which}; offers: quiz -> smaller offer -> thank-you'
          + (f'; STAND-IN IMAGES: {", ".join(standins)}' if standins else ''))


if __name__ == '__main__':
    main()
