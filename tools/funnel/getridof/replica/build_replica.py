#!/usr/bin/env python3
"""Get Rid Of — the replica funnel, /mouse-repellent-pouches/ (campaign 2721).

    python3 -I tools/funnel/getridof/replica/build_replica.py     # after build_lp.py and build_checkout.py

    product page (the brand's proven page, rebuilt as Get Rid Of)  ->  checkout  ->  offers  ->  thank-you

1. Copies campaigns/getridof/src/mouse-pouches to campaigns/getridof/src/mouse-repellent-pouches: the checkout, offer
   and thank-you pages are the same proven ones (they use campaign_asset / campaign_link, so they re-root themselves).
2. Puts campaign 2721's key in the copy's config.js and adds the funnel to _data/campaigns.json.
3. Adds Buy 3, Get 2 FREE to this funnel's checkout (shop_checkout.with_five_pack): the product page sells three
   bundles, the standard checkout only two.
4. Runs build_replica.mjs, which rebuilds the product page from exports/sofyre/offline/ and writes index.html.
5. Embeds the first gallery photo in the HTML and runs purge_css.mjs (one stylesheet with only the rules in use).

Never edit src/mouse-repellent-pouches by hand: it is regenerated. The key is never printed.
"""
import base64
import io
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import shop_checkout  # noqa: E402

ROOT = HERE.parents[3]
BASE = 'mouse-pouches'
SLUG = 'mouse-repellent-pouches'
SRC_CAMP = ROOT / 'campaigns/getridof/src' / BASE
CAMP = ROOT / 'campaigns/getridof/src' / SLUG
MARKER = '.generated-by-build_replica'
NAME = 'Get Rid Of - Rodent Repellent Pouches PDP'
CLONE_MANIFEST = ROOT / 'next-campaigns-create-runs/getridof/clone-2362-pdp/run-manifest.json'
# What the product page's bundle box shows (replica/pdp.js) must be what the checkout charges (shop_checkout.py).
HERO_INLINE = (560, 62)   # width and WebP quality of the first gallery photo embedded in the HTML (as on the sales page)
PAGE_PRICES = {'buy1': '22.49', 'buy3': '47.97', 'buy5': '64.95', 'ot1': '34.99', 'ot3': '69.99', 'ot5': '104.95'}


def sync():
    if CAMP.exists():
        if not (CAMP / MARKER).is_file(): raise SystemExit(f'{CAMP} exists and was not made by this script')
        shutil.rmtree(CAMP)
    # index.html: the lean sales page; lp/ images are kept (the checkout uses a few of them); pdp.js / pdp.css are rewritten
    shutil.copytree(SRC_CAMP, CAMP, ignore=shutil.ignore_patterns('index.html', 'pdp.js', 'pdp.css'))
    (CAMP / MARKER).write_text('Generated by tools/funnel/getridof/replica/build_replica.py from src/mouse-pouches. Do not edit: edit the generators.\n')
    left = [p.relative_to(CAMP).as_posix() for p in CAMP.rglob('*') if p.suffix in ('.html', '.js', '.css') and f'/{BASE}/' in p.read_text(errors='ignore')]
    if left: raise SystemExit(f'hard-coded /{BASE}/ paths in the copied funnel: {left}')


def campaign_key():
    """Campaign 2721's public key. Source of truth: the clone's run manifest (gitignored); mirrored into
    replica/campaign.json (committed, like the key in src/mouse-pouches/assets/config.js: every browser receives it)."""
    saved = HERE / 'campaign.json'
    if CLONE_MANIFEST.is_file():
        m = json.loads(CLONE_MANIFEST.read_text())
        c = m.get('campaign') or {}
        if c.get('api_key') and c.get('id') and m.get('inventory_complete'):
            saved.write_text(json.dumps({'campaign_id': c['id'], 'name': c.get('name'), 'cloned_from': m.get('source_campaign_id'), 'api_key': c['api_key']}, indent=2) + '\n')
    if not saved.is_file(): raise SystemExit('no campaign for this funnel: replica/campaign.json is missing')
    c = json.loads(saved.read_text())
    return c['api_key'], f"campaign {c['campaign_id']} ({c.get('name')})"


def configure():
    key, which = campaign_key()
    cfg = CAMP / 'assets/config.js'
    c, n = re.subn(r"(apiKey:\s*)(['\"])[^'\"]*\2", lambda m: f"{m.group(1)}'{key}'", cfg.read_text(), count=1)
    assert n == 1, 'apiKey line not found in config.js'
    cfg.write_text(c)
    data_f = ROOT / 'campaigns/getridof/_data/campaigns.json'
    data = json.loads(data_f.read_text())
    entry = dict(data[BASE])
    entry.update(name=NAME, description='Get Rid Of Rodent Repellent Pouches: natural 4-oil formula, mice gone in 72 hours, 90 days per pouch.')
    data[SLUG] = entry
    data_f.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    return which


def five_pack():
    co = CAMP / 'checkout.html'
    co.write_text(shop_checkout.with_five_pack(co.read_text()))
    # the Placement Guide download on the thank-you page comes with the 3-pack and the 5-pack
    rc = CAMP / 'receipt.html'
    r = rc.read_text()
    assert r.count("/3$/.test(sessionStorage.getItem('gro_bundle')") == 1, 'receipt guide rule'
    rc.write_text(r.replace("/3$/.test(sessionStorage.getItem('gro_bundle')", "/[35]$/.test(sessionStorage.getItem('gro_bundle')"))
    # the page's prices against the checkout's
    charged = {b[0]: b[3] for b in shop_checkout.BUNDLES + shop_checkout.FIVE}
    assert charged == PAGE_PRICES, f'checkout prices changed: {charged}'
    shown = json.loads((HERE / 'prices.json').read_text())
    for bid, row in shown.items():
        n = bid[3:]
        assert row['sub'][0] == '$' + charged['buy' + n] and row['one'][0] == '$' + charged['ot' + n], f'prices.json row {bid} does not match the checkout'


def webp(src, width, quality):
    im = Image.open(src).convert('RGB')
    if im.width > width: im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=quality, method=6)
    return buf.getvalue()


def small_images():
    """The header menu's banner (a 1.4 MB PNG in the source page) as a small WebP."""
    (CAMP / 'assets/pdp/gro-menu-banner.webp').write_bytes(webp(CAMP / 'assets/pdp/Buy_3-707070.png', 640, 76))


def embed_hero(html):
    """The first gallery photo travels inside the HTML, so the first screen paints without a second request."""
    tag = re.search(r'<img\b[^>]*\sdata-gro-hero=""[^>]*>', html)
    assert tag, 'first gallery photo not found'
    src = f'/{SLUG}/lp/hero-1.webp'
    assert tag.group(0).count(f'src="{src}"') == 1, 'first gallery photo: unexpected src'
    data = 'data:image/webp;base64,' + base64.b64encode(webp(CAMP / 'assets/lp/hero-1.webp', *HERO_INLINE)).decode()
    new = tag.group(0).replace(f'src="{src}"', f'src="{data}" data-gro-hd="{src}"').replace(' data-gro-hero=""', '')
    return html.replace(tag.group(0), new, 1)


def main():
    sync()
    which = configure()
    five_pack()
    small_images()
    subprocess.run(['node', str(HERE / 'build_replica.mjs')], check=True)
    page = CAMP / 'index.html'
    page.write_text(embed_hero(page.read_text()))
    subprocess.run(['node', str(HERE / 'purge_css.mjs')], check=True)   # last: one stylesheet with the rules the page uses
    html = page.read_text()
    if f'/{BASE}/' in html: raise SystemExit('the product page still links to the other funnel')
    print(f'replica funnel: {CAMP.relative_to(ROOT)} ({page.stat().st_size / 1e6:.2f} MB product page); api key: {which}')


if __name__ == '__main__':
    main()
