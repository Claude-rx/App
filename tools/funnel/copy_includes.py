"""The product page's long copy, from the stick page's own module (tools/persona/stick_copy.py), as Page Kit includes:
the buy box's tabs and the FAQ, so the funnel says exactly what the store's stick page says.

usage: python3 -I tools/funnel/copy_includes.py

Writes campaigns/skinofab/src/stick-funnel/_includes/sf-stick-tabs.html and sf-stick-faq.html (generated: edit
stick_copy.py, then run this). The storefront's "Can I buy just once?" answer is left out: it points to the store's
cart page, and every pack in this funnel ships with Automatic Refills.
"""
import html, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'persona'))
import stick_copy as SC

INC = ROOT / 'campaigns' / 'skinofab' / 'src' / 'stick-funnel' / '_includes'
HEAD = '{%- comment -%} GENERATED by tools/funnel/copy_includes.py from tools/persona/stick_copy.py; do not edit. {%- endcomment -%}\n'
STORE_ONLY = {'Can I buy just once?'}


def accordion(items, cls, first_open=False):
    out = [f'<div class="sf-acc {cls}">']
    for i, (q, a) in enumerate(items):
        body = a if a.lstrip().startswith('<') else f'<p>{html.escape(a, quote=False)}</p>'
        out.append(f'<details{" open" if first_open and i == 0 else ""}><summary>{html.escape(q, quote=False)}</summary>'
                   f'<div class="sf-acc__body">{body}</div></details>')
    out.append('</div>')
    return HEAD + '\n'.join(out) + '\n'


if __name__ == '__main__':
    (INC / 'sf-stick-tabs.html').write_text(accordion(SC.tabs(), 'sf-acc--tabs'))
    faq = [(q, a) for q, a in SC.FAQ['items'] if q not in STORE_ONLY]
    (INC / 'sf-stick-faq.html').write_text(accordion(faq, 'sf-acc--faq'))
    print(f'tabs {len(SC.tabs())}, faq {len(faq)}')
