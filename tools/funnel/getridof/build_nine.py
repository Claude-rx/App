"""Get Rid Of — the 9-reason listicle funnel, /mice-9-reasons/ (campaign 2796, a clone of 2362).

    python3 -I tools/funnel/getridof/build_nine.py     # after build_lp.py and build_checkout.py

    listicle (9 reasons)  ->  checkout  ->  home-plan quiz offer  --no-->  smaller offer  ->  thank-you

What is different from the 5-reason listicle funnel (build_listicle.py):
  * the page: nine/page.html + nine/n9.css, written from the review research in brand/getridof/research/
    (320 Amazon reviews of other brands' repellents, read on 16 Nov 2026) and the sources listed on the page;
  * the checkout: first and last name on one row and the short address form of the reference checkout (only the
    address line shows until it is typed);
  * the offers after the order: one page with a two-question home quiz that picks how many more packs the home needs
    (1, 2, 3 or 5 packs of the same product), then one smaller offer if the customer says no.

Content rules, same as the other pages: nothing is invented. Amazon quotes are word for word, from other brands'
listings, and are labelled as such. Customer quotes and photos are the brand's own, carried over from its pages.
No expert is shown unless brand/getridof/expert.json names a real person who approved the text (see its _readme).
Prices are never typed here: every price on the offer pages is rendered by the Campaign Cart SDK from campaign 2796.
"""
