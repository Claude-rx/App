#!/usr/bin/env python3
"""Get Rid Of — the listicle funnel, /mice-5-reasons/ (homeowner persona).

    python3 -I tools/funnel/getridof/build_listicle.py     # after build_lp.py and build_checkout.py

    listicle (this file)  ->  checkout  ->  offers  ->  thank-you

The checkout, offer and thank-you pages are the proven mouse-pouches ones: this script copies
campaigns/getridof/src/mouse-pouches to campaigns/getridof/src/mice-5-reasons (the pages use campaign_asset /
campaign_link, so they re-root themselves), then replaces the sales page with the listicle.

The listicle (listicle/page.html + listicle/ls.css) reuses the sales page's stylesheet, script, top bar, buy box,
how-it-works animation and footer, taken from lp/ at build time so the two pages cannot drift apart.

Campaign: the funnel uses its own Campaigns App campaign when one has been created for it (a clone of 2362 made by
next-campaigns-create, recorded in next-campaigns-create-runs/getridof/clone-2362-listicle/run-manifest.json). Until
then it runs on campaign 2362's key, so it works from the first deploy. The key is never printed.

Content rules, same as the sales page: nothing is invented here. Customer quotes are carried over from the brand's
original listicle and sales page; the photos are the brand's customer photos with the old brand name removed.
"""
import base64
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_lp as lp  # noqa: E402  (REVIEWS, webp, axon_head, SDK, tracking_tags)

ROOT = Path(__file__).resolve().parents[3]
HERE = ROOT / 'tools/funnel/getridof/listicle'
BASE = 'mouse-pouches'
SLUG = 'mice-5-reasons'
SRC_CAMP = ROOT / 'campaigns/getridof/src' / BASE
CAMP = ROOT / 'campaigns/getridof/src' / SLUG
SECTIONS = ROOT / 'brand/getridof/sections'
OUT = CAMP / 'assets/ls'
MARKER = '.generated-by-build_listicle'
NAME = 'Get Rid Of - Mouse Pouches Listicle'
CLONE_MANIFEST = ROOT / 'next-campaigns-create-runs/getridof/clone-2362-listicle/run-manifest.json'

# name -> (source in brand/getridof/sections, width, WebP quality[, centre-crop ratio])
IMAGES = {
    'mouse': ('gro-ls-mouse.png', 720, 72), 'mint': ('gro-ls-mint-vs-pellets.png', 640, 74),
    'hand': ('gro-ls-hand-pack.jpg', 720, 76), 'family': ('gro-ls-family-home.jpg', 720, 74), 'collage': ('gro-ls-collage.jpg', 720, 72),
}
HERO = ('gro-ls-hero.jpg', 640, 62, 16 / 9)     # inlined: the first screen paints from the HTML alone
WALL = [3, 'robert', 'tom', 4, 'amelia']                    # homeowner stories + two customer photos
THREAD = ['gary', 1, 'dale', 'thomas', 2, 'earl']           # short comments + the other two photos
FACE = {1: '80% 30%', 2: '50% 25%', 3: '72% 16%', 4: '50% 20%'}   # where the face is in lp/ugc-<n>.webp, for the round avatar
PHOTO_ALT = {1: 'A customer holding a bag of Rodent Repellent Pouches', 2: 'A customer outdoors holding a bag of Rodent Repellent Pouches',
             3: 'A customer showing a bag of Rodent Repellent Pouches', 4: 'A customer at home with a bag of Rodent Repellent Pouches'}


def sync():
    """Copy the mouse-pouches funnel to the listicle slug (everything but its sales page)."""
    if CAMP.exists():
        if not (CAMP / MARKER).is_file(): raise SystemExit(f'{CAMP} exists and was not made by this script')
        shutil.rmtree(CAMP)
    shutil.copytree(SRC_CAMP, CAMP, ignore=shutil.ignore_patterns('index.html', 'pdp.js'))   # pdp.js: the retired sales page's script, not used here
    (CAMP / MARKER).write_text('Generated by tools/funnel/getridof/build_listicle.py from src/mouse-pouches. Do not edit: edit the generators.\n')
    left = [p.relative_to(CAMP).as_posix() for p in CAMP.rglob('*') if p.suffix in ('.html', '.js', '.css') and f'/{BASE}/' in p.read_text(errors='ignore')]
    if left: raise SystemExit(f'hard-coded /{BASE}/ paths in the copied funnel: {left}')


def campaign_key():
    """The listicle campaign's own api key; None keeps the copied (campaign 2362) key.

    Source of truth: the clone's run manifest (gitignored). Its id, name and public campaign key are mirrored into
    listicle/campaign.json, which is committed, so the funnel can be rebuilt on a fresh checkout. (The same kind of
    key is already committed in src/mouse-pouches/assets/config.js: it is the public key every browser receives.)"""
    saved = HERE / 'campaign.json'
    if CLONE_MANIFEST.is_file():
        m = json.loads(CLONE_MANIFEST.read_text())
        c = m.get('campaign') or {}
        if c.get('api_key') and c.get('id') and m.get('inventory_complete'):
            saved.write_text(json.dumps({'campaign_id': c['id'], 'name': c.get('name'), 'cloned_from': m.get('source_campaign_id'), 'api_key': c['api_key']}, indent=2) + '\n')
    if saved.is_file():
        c = json.loads(saved.read_text())
        return c['api_key'], f"campaign {c['campaign_id']} ({c.get('name')})"
    return None, 'campaign 2362 (no listicle campaign created yet)'


def configure():
    key, which = campaign_key()
    cfg = CAMP / 'assets/config.js'
    c = cfg.read_text()
    if key:
        c, n = re.subn(r"(apiKey:\s*)(['\"])[^'\"]*\2", lambda m: f"{m.group(1)}'{key}'", c, count=1)
        assert n == 1, 'apiKey line not found in config.js'
        cfg.write_text(c)
    data_f = ROOT / 'campaigns/getridof/_data/campaigns.json'
    data = json.loads(data_f.read_text())
    entry = dict(data[BASE])
    entry.update(name=NAME, description='5 reasons traps, poison, sprays and plug-ins fail in a house, and the plant-oil pouches homeowners use instead.')
    data[SLUG] = entry
    data_f.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    return entry, which


def block(html, start, end):
    i = html.index(start); j = html.index(end, i) + len(end)
    return html[i:j]


def wall():
    by = {r[1]: r for r in lp.REVIEWS}
    unq = lambda v: re.sub(r'\s+', ' ', re.sub(r'[“”"]', '', v)).strip()
    stars = '<span class="sbx sbx--s" aria-label="5 out of 5 stars">' + '<i>★</i>' * 5 + '</span>'
    cards = []
    for item in WALL:
        if isinstance(item, int):
            cards.append(f'    <figure class="wc wc--ph"><img src="/{SLUG}/lp/ugc-{item}.webp" alt="{PHOTO_ALT[item]}" width="520" height="645" loading="lazy" decoding="async">'
                         '<figcaption>📷 Customer photo</figcaption></figure>')
        else:
            _, slug, who, where, pre, head, body = by[item]
            cards.append(f'    <article class="wc"><header><img src="/{SLUG}/lp/av-{slug}.webp" alt="" width="36" height="36" loading="lazy"><div><b>{who}</b>'
                         f'<span class="vb">✓ Verified Buyer</span></div></header>{stars}<h3>{unq(head)}</h3>'
                         f'<p class="wc__t">{unq(pre)} {unq(body)}</p><button type="button" class="wc__m" data-gro-more>Read more</button><small>{where}</small></article>')
    return '  <div class="wall">\n' + '\n'.join(cards) + '\n  </div>'


def thread():
    by = {r[1]: r for r in lp.REVIEWS}
    unq = lambda v: re.sub(r'\s+', ' ', re.sub(r'[“”"]', '', v)).strip()
    rows = []
    for item in THREAD:
        if isinstance(item, int):
            src = f'/{SLUG}/lp/ugc-{item}.webp'
            rows.append(f'    <div class="cm"><img class="cm__av" src="{src}" style="object-position:{FACE[item]}" alt="" width="40" height="40" loading="lazy">'
                        f'<div class="cm__c"><div class="cm__b"><b>Customer photo</b></div><img class="cm__ph" src="{src}" alt="{PHOTO_ALT[item]}" width="260" height="322" loading="lazy"></div></div>')
        else:
            _, slug, who, where, pre, head, body = by[item]
            rows.append(f'    <div class="cm"><img class="cm__av" src="/{SLUG}/lp/av-{slug}.webp" alt="" width="40" height="40" loading="lazy">'
                        f'<div class="cm__c"><div class="cm__b"><b>{who}</b><span>{unq(head)}</span></div><p class="cm__m">✓ Verified buyer</p></div></div>')
    return '\n'.join(rows)


def main():
    sync()
    camp, which = configure()
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for name, (src, width, q, *crop) in IMAGES.items():
        data, _ = lp.webp(SECTIONS / src, width, q, *crop)
        (OUT / f'{name}.webp').write_bytes(data); total += len(data)
    hero, _ = lp.webp(SECTIONS / HERO[0], *HERO[1:])
    (OUT / 'hero.webp').write_bytes(lp.webp(SECTIONS / HERO[0], 1100, 76, HERO[3])[0])

    pdp = (ROOT / 'tools/funnel/getridof/lp/page.html').read_text()
    top = block(pdp, '<header class="top">', '</header>')
    demo = block(pdp, '<figure class="demo">', '</figure>')
    buy = block(pdp, '<div class="ofr" id="gro-buy">', '<!--/ofr-->')     # the offer card (no prices; the choice is made in the checkout)
    assert buy.count('<div') == buy.count('</div>'), 'offer card block is not balanced'
    foot = block(pdp, '<footer class="ft">', '</footer>')

    key = camp.get('axon_event_key') or ''
    if key and not re.fullmatch(r'[0-9a-fA-F-]{36}', key): raise SystemExit('axon_event_key is not an event key')
    axon = lp.axon_head(camp)
    tags, on = lp.tracking_tags(camp)
    css = (ROOT / 'tools/funnel/getridof/lp/lp.css').read_text() + '\n' + (HERE / 'ls.css').read_text()
    css = re.sub(r'\s*\n\s*', '', re.sub(r'/\*.*?\*/', '', css, flags=re.S))
    js = re.sub(r'/\*.*?\*/', '', (ROOT / 'tools/funnel/getridof/lp/lp.js').read_text(), flags=re.S)
    js = re.sub(r'\n\s+', '\n', js).strip()
    html = (HERE / 'page.html').read_text()
    for token, value in (('@@CSS@@', css), ('@@JS@@', js), ('@@AXON_HEAD@@', axon), ('@@FUNNEL@@', camp['name']), ('@@TOP@@', top),
                         ('@@HERO_DATA@@', 'data:image/webp;base64,' + base64.b64encode(hero).decode()), ('@@DEMO@@', demo), ('@@BUY@@', buy),
                         ('@@WALL@@', wall()), ('@@THREAD@@', thread()), ('@@FOOTER@@', foot),
                         ('@@TRACKING@@', lp.SDK.replace('%VER%', camp['sdk_version']) + ('\n' + tags if tags else ''))):
        assert html.count(token) == 1, token
        html = html.replace(token, value)
    html = html.replace(f'/{BASE}/', f'/{SLUG}/')          # sales-page blocks and the script point at this funnel's own pages
    assert '@@' not in html and '{%' not in html and '{{' not in html and '</script' not in js.lower()
    assert f'/{BASE}' not in html and not re.search(r'sofyre', html, re.I)
    front = ('---\npage_layout: pdp.html\ntitle: "5 Reasons Everything You Tried Against Mice Failed – Get Rid Of"\npage_type: product\n'
             '# Generated by tools/funnel/getridof/build_listicle.py from tools/funnel/getridof/listicle/ — edit those, not this file.\n---\n')
    (CAMP / 'index.html').write_text(front + '{% raw %}' + html + '{% endraw %}\n', encoding='utf-8')
    print(f'wrote {CAMP / "index.html"}: {len(html) / 1024:.0f} KB (hero inline {len(hero) / 1024:.0f} KB, css {len(css) / 1024:.0f} KB, js {len(js) / 1024:.0f} KB); '
          f'{len(IMAGES)} listicle images, {total / 1024:.0f} KB lazy; tracking tags on: {on or "none"}; api key: {which}')


if __name__ == '__main__':
    main()
