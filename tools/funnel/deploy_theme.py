"""Put the built funnel (Campaign Page Kit's _site/stick-funnel/) into the SKINOFAB theme, so the store serves it.

usage: python3 -I tools/funnel/deploy_theme.py <page-kit _site/stick-funnel dir> <theme dir>
       e.g. python3 -I tools/funnel/deploy_theme.py campaigns/skinofab/_site/stick-funnel skinofab-theme

Each built page becomes a standalone theme template, templates/pages/page.<file>.html (no base layout: the Campaign
Cart SDK owns the page, the storefront's cart and scripts stay out of it), rendered by the store page of the same
slug at /<file>/ (store_pages.py creates those pages). The page's HTML sits inside {% verbatim %} so nothing in
it is read as template code; its local assets become theme assets, assets/sfc/<name>-<hash6>.<ext>, referenced
through {{ '...'|asset_url }}. NEXT's CDN serves every theme asset from one flat folder (assets/<basename>), so a
stylesheet's url() is rewritten to the bare name of the file it points to. Links between funnel pages and the SDK's
routing meta tags move from /stick-funnel/<file>/ to /<file>/.

Everything this writes is marked GENERATED and is replaced on every run: templates/pages/page.<file>.html for the
funnel's pages (stale ones with the marker are removed) and the whole assets/sfc/ folder.
"""
import hashlib, re, shutil, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import funnel as F

MARK = '{# GENERATED by tools/funnel/deploy_theme.py from campaigns/skinofab (Campaign Page Kit); do not edit. #}'
ASSET_DIR = 'sfc'
# a local URL in an attribute or a stylesheet: /stick-funnel/<path> (Page Kit's campaign_asset and campaign_link)
LOCAL = re.compile(r'/' + re.escape(F.SLUG) + r'/([A-Za-z0-9_./%-]+)')
CSS_URL = re.compile(r'url\(\s*([\'"]?)([^\'")]+)\1\s*\)')
# NEXT compiles every theme stylesheet with libsass, which reads min() and max() as its own functions and stops at
# mixed units ("Incompatible units: 'px' and 'vw'"). CSS function names are case-insensitive and Sass's are not, so the
# upper-case spelling passes through to the browser unchanged in meaning.
SASS_MINMAX = re.compile(r'(?<![\w-])(min|max)\(')


class Assets:
    def __init__(self, site, theme):
        self.site, self.out = site, theme / 'assets' / ASSET_DIR
        self.names, self.missing = {}, set()

    def name(self, rel):
        """The theme asset name for a file of the built site (rel: its path under _site/stick-funnel/)."""
        rel = rel.split('?')[0].split('#')[0]
        if rel in self.names: return self.names[rel]
        src = self.site / rel
        if not src.is_file(): raise SystemExit(f'missing asset {rel}')
        data = src.read_bytes()
        if src.suffix == '.css': data = SASS_MINMAX.sub(lambda m: m.group(1).upper() + '(', self.css(src, data.decode('utf-8'))).encode('utf-8')
        stem = re.sub(r'[^a-z0-9-]+', '-', src.stem.lower()).strip('-')[:48]
        name = f'{ASSET_DIR}-{stem}-{hashlib.sha1(data).hexdigest()[:6]}{src.suffix.lower()}'
        self.out.mkdir(parents=True, exist_ok=True)
        (self.out / name).write_bytes(data)
        self.names[rel] = name
        return name

    def css(self, path, text):
        """A stylesheet's local url()s as bare names: the CDN puts every theme asset in one folder."""
        def sub(m):
            q, url = m.group(1), m.group(2)
            if url.startswith(('data:', 'http:', 'https:', '//', '#')): return m.group(0)
            if url.startswith('/' + F.SLUG + '/'): rel = url[len(F.SLUG) + 2:]
            else: rel = (path.parent / url.split('?')[0].split('#')[0]).resolve().relative_to(self.site.resolve()).as_posix()
            if not (self.site / rel).is_file():       # the starter stylesheet names a few files it does not ship
                self.missing.add(rel)
                return m.group(0)
            return f'url({q}{self.name(rel)}{q})'
        return CSS_URL.sub(sub, text)


def template(html, assets, pages):
    def sub(m):
        rel = m.group(1)
        first = rel.split('/')[0]
        if first in pages and (rel == first or rel.startswith(first + '/')):       # a funnel page: the store's route
            return F.STORE_ROUTE + rel
        return '{% endverbatim %}{{ \'' + ASSET_DIR + '/' + assets.name(rel) + '\'|asset_url }}{% verbatim %}'
    body = LOCAL.sub(sub, html)
    if '{% endverbatim %}' in html: raise SystemExit('page carries a verbatim end tag')
    return MARK + '\n{% verbatim %}' + body + '{% endverbatim %}\n'


def main(site, theme):
    site, theme = Path(site), Path(theme)
    pages = {p['file'] for p in F.PAGES}
    shutil.rmtree(theme / 'assets' / ASSET_DIR, ignore_errors=True)
    assets = Assets(site, theme)
    tdir = theme / 'templates' / 'pages'
    for old in tdir.glob('page.*.html'):                     # earlier runs' pages that are no longer in the funnel
        if old.read_text(errors='ignore').startswith(MARK) and old.name[5:-5] not in pages: old.unlink()
    for f in sorted(pages):
        built = site / f / 'index.html'
        if not built.is_file(): raise SystemExit(f'not built: {built}')
        (tdir / f'page.{f}.html').write_text(template(built.read_text(encoding='utf-8'), assets, pages), encoding='utf-8')
    size = sum(p.stat().st_size for p in (theme / 'assets' / ASSET_DIR).iterdir())
    print(f'funnel: {len(pages)} templates, {len(assets.names)} assets ({size / 1e6:.1f} MB) in assets/{ASSET_DIR}/')
    if assets.missing: print('  stylesheet urls left as they are (no such file in the build):', ', '.join(sorted(assets.missing)))


if __name__ == '__main__':
    main(*sys.argv[1:3])
