"""Write the MedicLab Funnels theme's non-funnel templates: every storefront route (home, catalogue, product, cart,
search, blog, support, reviews, plain pages, 403/404/500) sends the visitor to the sales page, keeping the query string
(UTMs and click ids reach the funnel). The funnel's own pages are written by tools/funnel/deploy_theme.py
(FUNNEL=mediclab).

usage: python3 -I tools/mediclab/theme.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THEME = ROOT / 'mediclab-theme'
sys.path.insert(0, str(ROOT / 'tools' / 'funnel' / 'funnels'))
import mediclab as F  # noqa: E402  (the funnel's pages: tools/funnel/funnels/mediclab.py)
ENTRY = '/' + next(p['file'] for p in F.PAGES if p.get('entry')) + '/'
ROUTES = ['index.html', '403.html', '404.html', 'cart.html', 'search.html',
          'catalogue/index.html', 'catalogue/category.html', 'catalogue/product.html',
          'blog/index.html', 'blog/post.html',
          'support/index.html', 'support/category.html', 'support/article.html',
          'reviews/index.html', 'reviews/form.html', 'reviews/review.html']
MARK = '{# GENERATED by tools/mediclab/theme.py: campaign-only theme, this route goes to the sales page. #}'
PAGE = MARK + """
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex">
<meta name="ml-route" content="%%(route)s">
<title>MedicLab</title>
<script>location.replace('%(entry)s' + location.search + location.hash);</script>
<meta http-equiv="refresh" content="0;url=%(entry)s">
<style>body{font-family:system-ui,sans-serif;background:#0b2a1b;color:#fff;display:grid;place-items:center;min-height:100vh;margin:0}a{color:#e3f6a4}</style>
</head>
<body><p><a href="%(entry)s">Continue to MedicLab</a></p></body>
</html>
""" % {'entry': ENTRY}


# a server error must never redirect: a funnel page that fails to render would otherwise loop to itself
ERROR_500 = MARK.replace('this route goes to the sales page', 'server error page, no redirect') + """
<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex"><title>MedicLab: something went wrong</title>
<style>body{font-family:system-ui,sans-serif;background:#f5f1e8;color:#1f2421;display:grid;place-items:center;min-height:100vh;margin:0;text-align:center;padding:16px}a{color:#1d503a}</style>
</head><body><div><h1>Something went wrong on our side</h1><p>Please try again in a minute, or email <a href="mailto:hello@mediclab.us">hello@mediclab.us</a>.</p></div></body></html>
"""


def page_dispatch():
    """pages/page.html renders the funnel page by slug, and sends any other store page to the sales page. Each funnel
    page's template (page.<file>.html, written by deploy_theme.py) is inlined here, not included: on this store an
    {% include %} of another theme template fails the render (404), and a page's own template choice is not honoured
    in preview. The store pages keep an empty template, so preview and live render the same way."""
    out = [MARK.replace('this route goes to the sales page', 'store pages: funnel page by slug, else the sales page')]
    for n, p in enumerate(F.PAGES):
        f = p['file']
        tpl = (THEME / 'templates' / 'pages' / f'page.{f}.html').read_text()
        body = tpl.split('\n', 1)[1] if tpl.startswith('{# GENERATED') else tpl     # drop deploy_theme's marker line
        out.append(('{% if' if n == 0 else '{% elif') + f" page.slug == '{f}' %}}" + body)
    out.append('{% else %}' + PAGE.split('\n', 1)[1].replace('%(route)s', 'pages/page.html') + '{% endif %}')
    return '\n'.join(out) + '\n'


def main():
    (THEME / 'templates' / '500.html').write_text(ERROR_500)
    (THEME / 'templates' / 'pages' / 'page.html').write_text(page_dispatch())
    for r in ROUTES:
        p = THEME / 'templates' / r
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(PAGE.replace('%(route)s', r))
    print(f'theme: {len(ROUTES)} redirect templates -> {ENTRY}')


if __name__ == '__main__':
    main()
