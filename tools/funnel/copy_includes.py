"""The product page's long copy, from the stick page's own module (tools/persona/stick_copy.py), as Page Kit includes:
the buy box's tabs and the FAQ, so the funnel says exactly what the store's stick page says.

usage: python3 -I tools/funnel/copy_includes.py

Writes campaigns/skinofab/src/stick-funnel/_includes/ (generated: edit stick_copy.py, then run this):
  sf-stick-tabs.html    the buy box's tabs
  sf-stick-faq.html     the FAQ, with the funnel's own answers where the store's point elsewhere (FUNNEL_FAQ)
  sf-stick-story.html   the problem, its root and the solution (TWIN['problem'])
  sf-stick-howto.html   twist, dot, buff: the four steps with their photos (TWIN['cards'])
  sf-stick-expect.html  what to expect (TWIN['results'])
  sf-stick-note.html    the brand's own note, signed as the brand (TWIN['note'])
"""
import html, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'persona'))
import stick_copy as SC

INC = ROOT / 'campaigns' / 'skinofab' / 'src' / 'stick-funnel' / '_includes'
HEAD = '{%- comment -%} GENERATED by tools/funnel/copy_includes.py from tools/persona/stick_copy.py; do not edit. {%- endcomment -%}\n'
# the store's answers that point to its cart page (where a pack can be set to a one-time purchase); in the funnel every
# pack ships with Automatic Refills, so she buys once by cancelling before her first refill. Each refill is the same
# package as her first order (the campaign's package 2 is "2 sticks + free Lymphatic Brush"), so the 2-stick refill
# comes with a brush too.
FUNNEL_FAQ = {
    'Can I buy just once?':
        f'Every pack here comes with Automatic Refills. If you only want this one, order it, then email {SC.EMAIL} any '
        'time before your next refill: we cancel it, nothing more is charged, and your 30-day money-back guarantee stays.',
    'How do Automatic Refills work?':
        'Your pack ships again on a set schedule, at the refill price: $37 every 28 days for 1 stick, $47 every 56 days for '
        '2 sticks with a Lymphatic Brush. Each refill is the same pack as your first order. We email you before every '
        f'refill. To skip, delay or cancel, just email {SC.EMAIL}: no minimum, no fees, and a person replies within one '
        'business day. Every refill is covered by the same 30-day money-back guarantee.',
}


def img(name, alt, w=1080, h=1080, cls=''):
    return (f'<img{f' class="{cls}"' if cls else ""} src="{{{{ \'images/sf/{name}.jpg\' | campaign_asset }}}}" '
            f'alt="{html.escape(alt)}" width="{w}" height="{h}" loading="lazy" decoding="async">')


def mark(lead, hl):
    return f'{html.escape(lead, quote=False)} <span class="sf-mark">{html.escape(hl, quote=False)}</span>'


def story():
    t = SC.TWIN['problem']
    e = lambda x: html.escape(x, quote=False)
    pains = ''.join(f'<li>{e(x)}</li>' for x in t['pains'])
    causes = ''.join(f'<div class="sf-cause"><strong>{e(a)}</strong><p>{e(b)}</p></div>' for a, b in t['causes'])
    fixes = ''.join(f'<li><strong>{e(a)}</strong> {e(b)}</li>' for a, b in t['fixes'])
    return HEAD + f"""<section class="sf-sec sf-story" id="why">
  <div class="sf-two">
    {img('problem', t['photo_alt'], 1254, 1254, 'sf-round')}
    <div>
      <p class="sf-eyebrow">{e(t['problem'][0])}</p>
      <h2 class="sf-h2">{mark(t['problem'][1], t['problem'][2])}</h2>
      <p>{e(t['lede'])}</p>
      <ul class="sf-pains">{pains}</ul>
      <p><strong>{e(t['close'])}</strong></p>
    </div>
  </div>
  <div class="sf-root">
    <p class="sf-eyebrow">{e(t['root'][0])}</p>
    <h2 class="sf-h2">{mark(t['root'][1], t['root'][2])}</h2>
    <div class="sf-causes">{causes}</div>
    <p class="sf-root__end">{e(t['root_end'])}</p>
  </div>
  <div class="sf-two sf-solution">
    <div>
      <p class="sf-eyebrow">{e(t['solution'][0])}</p>
      <h2 class="sf-h2">{mark(t['solution'][1], t['solution'][2])}</h2>
      <p>{e(t['solution_lede'])}</p>
      <ul class="sf-fixes">{fixes}</ul>
      <a class="sf-btn" href="#buy">{e(t['button']).upper()}</a>
      <p class="sf-fine">{e(t['note'])}</p>
    </div>
    {img('stick-card', t['product_alt'], cls='sf-round')}
  </div>
</section>
"""


def howto():
    c = SC.TWIN['cards']
    e = lambda x: html.escape(x, quote=False)
    files = {'twist': 'step-twist', 'dots': 'step-dots', 'blend': 'step-blend', 'apply-cheek': 'step-apply-cheek'}
    items = ''.join(f'<li class="sf-step">{img(files[i["img"]], i["alt"])}<strong>{n}. {e(i["title"])}</strong><p>{e(i["text"])}</p></li>'
                    for n, i in enumerate(c['items'], 1))
    return HEAD + f"""<section class="sf-sec" id="how-to">
  <p class="sf-eyebrow" style="text-align:center">{e(c['eyebrow'])}</p>
  <h2 class="sf-h2" style="text-align:center">{e(c['title'])}</h2>
  <ol class="sf-howto">{items}</ol>
</section>
"""


def expect():
    r = SC.TWIN['results']
    e = lambda x: html.escape(x, quote=False)
    cards = ''.join(f'<div class="sf-expect__card"><b>{e(a)}</b><strong>{e(b)}</strong><span>{e(c)}</span></div>' for a, b, c in r['cards'])
    return HEAD + f"""<section class="sf-sec sf-expect">
  <h2 class="sf-h2" style="text-align:center">{e(r['title'])}</h2>
  <div class="sf-expect__grid">{cards}</div>
</section>
"""


def note():
    n = SC.TWIN['note']
    paras = ''.join(f'<p>{x}</p>' for x in n['paragraphs'])          # (the copy's own <strong>)
    return HEAD + f"""<section class="sf-sec sf-sec--cream">
  <div class="sf-sec__in sf-two">
    {img(n['photo'], n['photo_alt'], cls='sf-round')}
    <div>
      <p class="sf-eyebrow">{html.escape(n['eyebrow'], quote=False)}</p>
      <h2 class="sf-h2">{mark(n['headline_lead'], n['headline_mark'])}</h2>
      {paras}
      <p class="sf-sign"><strong>{html.escape(n['name'], quote=False)}</strong> · {html.escape(n['role'], quote=False)}</p>
    </div>
  </div>
</section>
"""


def accordion(items, cls, first_open=False):
    out = [f'<div class="sf-acc {cls}">']
    for i, (q, a) in enumerate(items):
        body = a if a.lstrip().startswith('<') else f'<p>{html.escape(a, quote=False)}</p>'
        out.append(f'<details{" open" if first_open and i == 0 else ""}><summary>{html.escape(q, quote=False)}</summary>'
                   f'<div class="sf-acc__body">{body}</div></details>')
    out.append('</div>')
    return HEAD + '\n'.join(out) + '\n'


if __name__ == '__main__':
    (INC / 'sf-stick-tabs.html').write_text(accordion(SC.tabs(), 'sf-acc--tabs'))
    faq = [(q, FUNNEL_FAQ.get(q, a)) for q, a in SC.FAQ['items']]
    assert all(q in dict(SC.FAQ['items']) for q in FUNNEL_FAQ), 'a FUNNEL_FAQ question is no longer in stick_copy.FAQ'
    (INC / 'sf-stick-faq.html').write_text(accordion(faq, 'sf-acc--faq'))
    for name, fn in (('story', story), ('howto', howto), ('expect', expect), ('note', note)):
        (INC / f'sf-stick-{name}.html').write_text(fn())
    print(f'tabs {len(SC.tabs())}, faq {len(faq)}, story, howto, expect, note')
