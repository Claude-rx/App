"""The flash trial funnel's gate: what the theme serves says what campaign 2251 charges, and nothing of the APF funnel's
offer or the store's packs is left in it.

usage: python3 -I tools/funnel/trial/check_trial.py [theme dir] [--live]

Reads the theme templates the store serves (templates/pages/page.<file>.html for every page of funnels/trial.py), the
Page Kit source (campaigns/skinofab/src/trial-funnel) and the CampaignSpec (campaign-spec.trial.json, the campaign's
own read). --live also prices every page's offer through the Campaign Cart API (POST /api/v1/carts/calculate/, the
campaign's public key from config.js, never printed): the trial with FLASH50 must be $19.97, without it $39.97, and each
offer what its page says. Exit 1 with every failure listed.
"""
import json, os, re, subprocess, sys
from pathlib import Path

os.environ['FUNNEL'] = 'trial'
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import funnel as F

ROOT = HERE.parents[2]
PROJECT = ROOT / 'campaigns' / 'skinofab'
SRC = PROJECT / 'src' / F.SLUG
T = F.TRIAL
TODAY, REGULAR = f"${T['today']:.2f}", f"${T['regular']:.2f}"
fails = []


def ok(cond, msg):
    if not cond: fails.append(msg)


def tpl(theme, pid):
    p = theme / 'templates' / 'pages' / f"page.{F.BY_ID[pid]['file']}.html"
    ok(p.is_file(), f'{pid}: no theme template {p.name}')
    return p.read_text(encoding='utf-8') if p.is_file() else ''


def text(html):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', re.sub(r'<style.*?</style>|<script.*?</script>|<template.*?</template>', '', html, flags=re.S)))


def check_spec():
    spec = json.loads((PROJECT / F.SPEC_FILE).read_text())
    ok(spec['campaign']['ref_id'] == F.CAMPAIGN_REF, f"spec: campaign {spec['campaign']['ref_id']} is not {F.CAMPAIGN_REF}")
    co = next(p for p in spec['funnels'][0]['pages'] if p['id'] == 'checkout')
    pk = co['packages'][0]
    ok(pk['ref_id'] == T['package'] and float(pk['price']) == T['regular'] and pk.get('is_recurring') and float(pk.get('price_recurring') or 0) == T['regular']
       and pk.get('interval') == T['every'], f'spec: the trial package is not {REGULAR} refilling every {T["every"]}: {pk}')
    offer = next(o for o in spec['offers'] if o['ref_id'] == F.VOUCHER[T['voucher']])
    ok(offer['code'] == T['voucher'] and float(offer['benefit']['value']) == T['off'], f'spec: {T["voucher"]} is not {T["off"]}% off: {offer}')
    for pid, op in F.OFFER_PAGES.items():
        live = {p['ref_id']: p for p in next(p for p in spec['funnels'][0]['pages'] if p['id'] == pid)['packages']}
        for t in op['tiers']:
            ok(t['ref'] in live, f'{pid}: package {t["ref"]} is not on the page in the spec')
            if t['ref'] in live and not t.get('voucher'): ok(float(live[t['ref']]['price']) == t['price'], f'{pid}: {t["ref"]} is {live[t["ref"]]["price"]}, the page says {t["price"]}')
    return spec


def check_pdp(theme):
    h = tpl(theme, 'offer')
    ok(h.startswith('{# GENERATED by tools/funnel/trial/pdp_copy.py'), 'product page: not the pdp_copy.py output')
    for need in ('Flash trial offer · Limited time, today only', 'Love it or your money back', 'Refill reminder', 'Cancel any time',
                 f'Renews at <b data-sft-renew="">{REGULAR}/mo</b>', f'{F.route("checkout", served=True)}?forceBundleId=trial"', 'forceBundleId=trial-regular',
                 'forceBundleId=trial-3"', 'forceBundleId=trial-5"', 'Buy 2, get 1 FREE', 'Buy 3, get 2 FREE', '$66.97', '$99.97', '$119.91', '$199.85',
                 'sf_trial_end', 'data-sf-trial-clock', '"page_view"', '"view_item"', '"add_to_cart"', 'id="apf-buy"',
                 '{% with product=settings.sf_p_color_changing_foundation %}'):
        ok(need in h, f'product page: missing {need!r}')
    t = text(h)
    for bad in (r'\$37\b', r'\$47\b', r'\$57\b', r'\$59\b', 'Add to Cart', 'Choose your pack', 'every 28 days', 'One-time purchase'):
        ok(not re.search(bad, t), f'product page: store residue {bad!r}')
    ok(f'{TODAY}' in t and REGULAR in t, 'product page: the trial prices are not both on it')


def check_checkout(theme):
    h = tpl(theme, 'checkout')
    cards = re.findall(r'<div data-next-bundle-card data-next-bundle-id="([\w-]+)"([^>]*)>', h)
    ids = {c[0]: c[1] for c in cards}
    ok(set(ids) == {'trial', 'trial-regular', 'trial-3', 'trial-5'}, f'checkout: cards {sorted(ids)}, want trial, trial-regular, trial-3, trial-5')
    for k in F.PACKS:
        a = ids.get(k['bundle'], '')
        ok(f'"packageId":{k["package"]},' in a and 'vouchers' not in a, f'checkout: card {k["bundle"]} is not package {k["package"]} without a code')
    ok('data-next-bundle-vouchers="FLASH50"' in ids.get('trial', ''), 'checkout: the trial card does not carry FLASH50')
    ok('vouchers' not in ids.get('trial-regular', ''), 'checkout: the regular card carries a code')
    for b in ('trial', 'trial-regular'): ok('"packageId":1,' in ids.get(b, '') and '"quantity":1' in ids.get(b, ''), f'checkout: card {b} is not one of package 1')
    ok('data-next-selected="true"' in ids.get('trial', ''), 'checkout: the trial card is not the default')
    ok("var K = 'sf_trial_end'" in h and "want = over ? 'trial-regular' : 'trial'" in h, 'checkout: the inline clock that picks the card is missing')
    i_clock, i_sdk = h.find("var K = 'sf_trial_end'"), h.find('campaign-cart@v')
    ok(i_clock > i_sdk > 0 or i_clock > 0, 'checkout: no clock')
    ok('data-template="exit-intent"' not in h, 'checkout: an exit pop is in the page')
    ok('data-next-coupon' not in h, 'checkout: a coupon box is in the page')
    ok(not re.search(r'value="(?:link|klarna)"', h), 'checkout: a Link or Klarna radio is in the page')
    ok('<meta name="next-success-url" content="/trial-offer-1/">' in h, 'checkout: next-success-url is not /trial-offer-1/')
    t = text(h)
    for need in ('Flash trial offer · Limited time, today only', 'Love it or your money back', 'Renews at $39.97/mo', f'{REGULAR} every month', 'Step 1: Choose your plan',
                 '$66.97 every 3 months', '$99.97 every 5 months'):
        ok(need in t, f'checkout: missing {need!r}')
    for bad in ('every 28 days', 'every 84 days', 'every 140 days', '$33.97 every', 'APF10', 'Choose your pack'):
        ok(bad not in t, f'checkout: APF residue {bad!r}')


def check_offers(theme):
    for pid in ('offer-1', 'offer-2', 'offer-2b', 'brush-offer', 'brush-offer-b'):
        h, pg = tpl(theme, pid), F.BY_ID[pid]
        ok(f'<meta name="next-upsell-accept-url" content="/{F.BY_ID[pg["accept"]]["file"]}/">' in h, f'{pid}: accept route')
        ok(f'<meta name="next-upsell-decline-url" content="/{F.BY_ID[pg["decline"]]["file"]}/">' in h, f'{pid}: decline route')
        for t in F.OFFER_PAGES[pid]['tiers']:
            ok(re.search(r'"packageId"\s*:\s*' + str(t['ref']) + r'\b', h) or f'data-next-package-id="{t["ref"]}"' in h, f'{pid}: package {t["ref"]} is not on the page')
            if t.get('voucher'): ok(t['voucher'] in h, f'{pid}: code {t["voucher"]} is not on the page')
            ok(f"${t['price']:.2f}" in h or f"${t['price']:.0f}" in h, f'{pid}: price {t["price"]} is not on the page')
        for bad in ('/apf-funnel/', 'foundation-offer-', 'lymphatic-brush-offer', 'foundation-thank-you', 'adaptive-foundation-offer/', 'APF40', 'APF50', '"BRUSH40"', '"BRUSH60"', 'Sales page price'):
            ok(bad not in h, f'{pid}: APF residue {bad!r}')
        ok('/adaptive-foundation-trial/' in h, f'{pid}: the no-order note does not link the trial page')


def check_thank_you(theme):
    h = tpl(theme, 'thank-you')
    ok('Then $39.97 every month, until you cancel.' in h, 'thank-you: the trial bottle\'s renewal is not $39.97 every month')
    ok('Then $66.97 every 3 months' in h and 'Then $99.97 every 5 months' in h, 'thank-you: the packs\' renewals are not on it')
    for bad in ('every 28 days', 'every 84 days', 'every 140 days', 'adaptive-foundation-offer/'):
        ok(bad not in h, f'thank-you: APF residue {bad!r}')


def check_key():
    key = lambda p: (re.search(r"apiKey:\s*'([^']+)'", p.read_text()) or [None, None])[1]
    mine, apf = key(SRC / 'assets' / 'config.js'), key(PROJECT / 'src' / 'apf-funnel' / 'assets' / 'config.js')
    ok(mine and mine != apf, 'config.js: the trial funnel uses no key of its own (it must be campaign 2251\'s)')
    return mine


def cart(key, lines, vouchers=(), upsell=False):
    body = json.dumps({'lines': lines, 'currency': 'USD', 'vouchers': list(vouchers)})
    url = 'https://campaigns.apps.29next.com/api/v1/carts/calculate/' + ('?upsell=true' if upsell else '')
    out = subprocess.run(['curl', '-sS', '-m', '60', '-X', 'POST', url, '-H', 'Content-Type: application/json', '-H', f'Authorization: {key}', '-d', body],
                         capture_output=True, text=True).stdout
    try: return json.loads(out)
    except ValueError: return {'error': out[:200]}


def check_live(key):
    total = lambda r: float(r.get('total_incl_tax') or r.get('total') or -1)
    r = cart(key, [{'package_id': T['package'], 'quantity': 1}], [T['voucher']])
    ok(total(r) == T['today'], f'live: the trial with {T["voucher"]} is {total(r)}, not {T["today"]} ({str(r)[:160]})')
    r = cart(key, [{'package_id': T['package'], 'quantity': 1}])
    ok(total(r) == T['regular'], f'live: the trial without a code is {total(r)}, not {T["regular"]}')
    for k in F.PACKS:
        r = cart(key, [{'package_id': k['package'], 'quantity': 1}])
        ok(total(r) == k['price'], f'live: pack {k["bundle"]} is {total(r)}, the page says {k["price"]}')
    for pid, op in F.OFFER_PAGES.items():
        for t in op['tiers']:
            r = cart(key, [{'package_id': t['ref'], 'quantity': 1}], [t['voucher']] if t.get('voucher') else [], upsell=True)
            ok(total(r) == t['price'], f'live: {pid} {t["key"]} is {total(r)}, the page says {t["price"]}')


if __name__ == '__main__':
    theme = Path(next((a for a in sys.argv[1:] if not a.startswith('--')), ROOT / 'skinofab-theme'))
    check_spec(); check_pdp(theme); check_checkout(theme); check_offers(theme); check_thank_you(theme)
    key = check_key()
    if '--live' in sys.argv and key: check_live(key)
    if fails:
        print('check_trial: FAIL'); [print('  - ' + f) for f in fails]; sys.exit(1)
    print(f"check_trial: {len(F.PAGES)} pages ok (trial {TODAY} then {REGULAR}/mo{', priced live' if '--live' in sys.argv else ''})")
