def wrap_block(src, name):
    """Run a block inside the product setting's with (a page has no product in its context)."""
    m = re.search(r'\{% block ' + name + r' %\}(.*?)\{% endblock ' + name + r' %\}', src, re.S)
    assert m, f'no block {name}'
    return src[:m.start(1)] + PRODUCT + m.group(1) + '{% endwith %}' + src[m.end(1):]


def block_end(s, start):
    depth = 0
    for m in re.finditer(r'<div\b|</div>', s[start:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0: return start + m.end()
    raise SystemExit('unbalanced buy box')


def sub1(pattern, repl, s, flags=0):
    out, n = re.subn(pattern, lambda m: repl, s, count=1, flags=flags)
    if n != 1: raise SystemExit(f'pdp_copy: not found in the store page: {pattern[:90]}')
    return out


