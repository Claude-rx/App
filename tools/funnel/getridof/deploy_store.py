#!/usr/bin/env python3
"""Serve the Get Rid Of mouse-pouches funnel from the store itself (getridof.shop / getridof.29next.store).

    python3 -I tools/funnel/getridof/deploy_store.py <theme dir>            # write templates + assets into a theme copy
    python3 -I tools/funnel/getridof/deploy_store.py <theme dir> --push     # ...then ntk-push only those files to theme 11
                                                                           #    and create/update the 4 store pages

Input: the Page Kit build, campaigns/getridof/_site/mouse-pouches/ (run `npx campaign-build` first).
Each built page becomes its own page template, templates/pages/page.<slug>.html, rendered by a store page whose
`template` is that slug (the theme's shared page.html router is not touched):

    /mouse-pouches/                   sales page (PDP)
    /mouse-pouches-checkout/          checkout, one-time
    /mouse-pouches-checkout-refill/   checkout, Automatic Refills
    /mouse-pouches-special-offer/     post-purchase upsell (one more pack, 40% off)
    /mouse-pouches-thank-you/         receipt

The HTML sits inside {% verbatim %}; local files become theme assets assets/gromp/gromp-<name>-<hash6>.<ext> through
{{ '...'|asset_url }}. NEXT's CDN serves theme assets from one flat folder, so stylesheet url()s become bare names, and
links between pages (in HTML and in pdp.js) move to the store routes above. Every file written carries the GENERATED
marker and is replaced on each run. The Admin token is the proxy-injected one; nothing prints it.
"""
import hashlib, json, re, shutil, subprocess, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SITE = ROOT / 'campaigns/getridof/_site/mouse-pouches'
SLUG = 'mouse-pouches'
STORE = 'https://getridof.29next.store'
THEME_ID = 11
ASSET_DIR = 'gromp'
PAGES = {  # built page dir ('' = index) -> store slug, title
    '': ('mouse-pouches', 'Rodent Repellent Pouches'),
    'checkout': ('mouse-pouches-checkout', 'Secure Checkout'),
    'checkout-refill': ('mouse-pouches-checkout-refill', 'Secure Checkout — Automatic Refills'),
    'upsell': ('mouse-pouches-special-offer', 'One More Pack, 40% Off'),
    'receipt': ('mouse-pouches-thank-you', 'Thank You'),
}
MARK = '{# GENERATED by tools/funnel/getridof/deploy_store.py from campaigns/getridof (mouse-pouches); do not edit. #}'
LOCAL = re.compile(r'/' + SLUG + r'/([A-Za-z0-9_./%-]*)')
CSS_URL = re.compile(r'url\(\s*([\'"]?)([^\'")]+)\1\s*\)')
SASS_MINMAX = re.compile(r'(?<![\w-])(min|max)\(')


def route(rel):
    """A funnel page path (rel under /mouse-pouches/) -> its store route, else None."""
    first = rel.split('/')[0] if rel else ''
    if first in PAGES and (rel in (first, first + '/') or (first == '' and rel == '')):
        return '/' + PAGES[first][0] + '/'
    return None


def js_routes(text):
    for d, (slug, _) in sorted(PAGES.items(), key=lambda kv: -len(kv[0])):
        text = text.replace(f"'/{SLUG}/{d + '/' if d else ''}'", f"'/{slug}/'")
    return text


class Assets:
    def __init__(self, theme):
        self.out = theme / 'assets' / ASSET_DIR
        shutil.rmtree(self.out, ignore_errors=True)
        self.out.mkdir(parents=True)
        self.names = {}

    def name(self, rel):
        rel = rel.split('?')[0].split('#')[0]
        if rel in self.names: return self.names[rel]
        src = SITE / rel
        if not src.is_file(): raise SystemExit(f'missing asset {rel}')
        data = src.read_bytes()
        if src.suffix == '.css':
            data = SASS_MINMAX.sub(lambda m: m.group(1).upper() + '(', self.css(src, data.decode('utf-8'))).encode()
        elif src.suffix == '.js':
            data = js_routes(data.decode('utf-8')).encode()
        stem = re.sub(r'[^a-z0-9-]+', '-', src.stem.lower()).strip('-')[:48]
        name = f'{ASSET_DIR}-{stem}-{hashlib.sha1(data).hexdigest()[:6]}{src.suffix.lower()}'
        (self.out / name).write_bytes(data)
        self.names[rel] = name
        return name

    def css(self, path, text):
        def sub(m):
            q, url = m.group(1), m.group(2)
            if url.startswith(('data:', 'http:', 'https:', '//', '#')): return m.group(0)
            rel = url[len(SLUG) + 2:] if url.startswith(f'/{SLUG}/') else \
                (path.parent / url.split('?')[0].split('#')[0]).resolve().relative_to(SITE.resolve()).as_posix()
            if not (SITE / rel).is_file(): return m.group(0)
            return f'url({q}{self.name(rel)}{q})'
        return CSS_URL.sub(sub, text)


LINK_CSS = re.compile(r'<link\b[^>]*\bhref="/' + SLUG + r'/([^"]+\.css)"[^>]*>')


def inline_css(html):
    """Local stylesheets go inline: the theme compiles every .css asset with libsass, which rejects modern CSS the
    page uses. url()s are made absolute (/mouse-pouches/<rel>) so the asset rewrite below turns them into asset_url."""
    def sub(m):
        rel = m.group(1); path = SITE / rel
        if 'stylesheet' not in m.group(0) or not path.is_file(): return m.group(0)
        def u(x):
            q, url = x.group(1), x.group(2)
            if url.startswith(('data:', 'http:', 'https:', '//', '#', '/')): return x.group(0)
            r = (path.parent / url.split('?')[0].split('#')[0]).resolve()
            try: r = r.relative_to(SITE.resolve()).as_posix()
            except ValueError: return x.group(0)
            return f'url({q}/{SLUG}/{r}{q})' if (SITE / r).is_file() else x.group(0)
        css = CSS_URL.sub(u, path.read_text(encoding='utf-8'))
        if '</style' in css: raise SystemExit(f'{rel} contains </style')
        return f'<style data-src="{rel}">' + css + '</style>'
    return LINK_CSS.sub(sub, html)


def template(html, assets):
    html = inline_css(html)
    if '{% endverbatim %}' in html: raise SystemExit('page carries a verbatim end tag')
    def sub(m):
        rel = m.group(1)
        r = route(rel)
        if r: return r
        return "{% endverbatim %}{{ '" + ASSET_DIR + '/' + assets.name(rel) + "'|asset_url }}{% verbatim %}"
    return MARK + '\n{% verbatim %}' + LOCAL.sub(sub, html) + '{% endverbatim %}\n'


def api(method, path, body=None):
    req = urllib.request.Request(f'{STORE}/api/admin/{path}', method=method, data=json.dumps(body).encode() if body is not None else None,
                                 headers={'Authorization': 'Bearer proxy-injected', 'X-29next-API-Version': '2024-04-01', 'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=60) as r: return json.loads(r.read() or b'{}')


def main(theme, push):
    theme = Path(theme)
    tdir = theme / 'templates' / 'pages'
    assets = Assets(theme)
    written = []
    for d, (slug, _) in PAGES.items():
        built = SITE / d / 'index.html' if d else SITE / 'index.html'
        if not built.is_file(): raise SystemExit(f'not built: {built}')
        out = tdir / f'page.{slug}.html'
        if out.exists() and not out.read_text(errors='ignore').startswith(MARK): raise SystemExit(f'{out} exists and is not ours')
        out.write_text(template(built.read_text(encoding='utf-8'), assets), encoding='utf-8')
        written.append(out.relative_to(theme).as_posix())
    files = written + sorted(f'assets/{ASSET_DIR}/{n}' for n in set(assets.names.values()))
    left = [f for f in written if '/mouse-pouches/' in (theme / f).read_text()]
    if left: raise SystemExit(f'unrewritten /mouse-pouches/ paths in {left}')
    size = sum((theme / f).stat().st_size for f in files)
    print(f'{len(written)} templates, {len(assets.names)} assets, {size / 1e6:.1f} MB')
    if not push: return
    for i in range(0, len(files), 40):
        r = subprocess.run(['ntk', 'push', '-a', 'proxy-injected', '-s', STORE, '-t', str(THEME_ID), *files[i:i + 40]], cwd=theme, capture_output=True, text=True)
        if r.returncode or 'ERROR' in (r.stdout + r.stderr): raise SystemExit(f'ntk push failed:\n{(r.stdout + r.stderr)[-2000:]}')
        print(f'pushed {min(i + 40, len(files))}/{len(files)}')
    existing = {p['slug']: p for p in api('GET', 'pages/?limit=100')['results']}
    for d, (slug, title) in PAGES.items():
        body = {'title': title, 'slug': slug, 'template': slug, 'meta_title': f'{title} | Get Rid Of'}
        if slug in existing: api('PATCH', f"pages/{existing[slug]['id']}/", body); print('updated page', slug)
        else: api('POST', 'pages/', {**body, 'content': '<p>Rendered by the theme template.</p>'}); print('created page', slug)


if __name__ == '__main__':
    main(sys.argv[1], '--push' in sys.argv)
